import streamlit as st

SUPPORTED_LANGS = ["Español", "English"]

def get_lang() -> str:
    """Devuelve el idioma actual de la sesión ('es' o 'en')."""
    return st.session_state.get("_lang", "es")

def set_lang(lang: str):
    """Establece el idioma de la sesión."""
    st.session_state["_lang"] = lang

def t(key: str, **kwargs) -> str:
    """Traduce una clave al idioma actual. Acepta kwargs para f-string substitution."""
    lang = get_lang()
    text = TRANSLATIONS.get(lang, TRANSLATIONS["es"]).get(key)
    if text is None:
        # Fallback al español si no existe traducción
        text = TRANSLATIONS["es"].get(key, key)
    if kwargs:
        try:
            text = text.format(**kwargs)
        except (KeyError, IndexError):
            pass
    return text


